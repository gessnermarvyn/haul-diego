window.lookupZip = function (zip) {
  var key = String(zip || "").replace(/\D/g, "").slice(0, 5);
  if (key.length !== 5) return { ok: false, reason: "invalid" };
  if (window.SD_ZIPS[key]) return { ok: true, zip: key, name: window.SD_ZIPS[key] };
  return { ok: false, zip: key, reason: "outside" };
};
